export function t(key, vars) {
  const lang = store.settings.lang;
  let s = (S[lang] && S[lang][key]) ?? S.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll('{' + k + '}', vars[k]);
  return s;
}
export function lang() { return store.settings.lang; }
